/**
 * Generates the secrets a new OpenHaul instance needs.
 *
 * Writes .env.local if it does not exist, so nobody ever ships the defaults.
 * Run with `node scripts/generate-secrets.mjs`.
 */
import { randomBytes } from 'node:crypto';
import { access, writeFile } from 'node:fs/promises';
import path from 'node:path';

const target = path.join(process.cwd(), '.env.local');

const exists = await access(target).then(
  () => true,
  () => false,
);

if (exists && !process.argv.includes('--force')) {
  console.error(`${target} already exists. Pass --force to overwrite (this invalidates all data).`);
  process.exit(1);
}

const key = (bytes = 32) => randomBytes(bytes).toString('base64');

const contents = `# Generated by scripts/generate-secrets.mjs
# Keep this file out of version control. chmod 600 it on a server.

# ---- database ----
# A local file by default. Point at libSQL/Turso by changing the URL.
DATABASE_URL="file:./data/openhaul.db"
# DATABASE_AUTH_TOKEN=""

# Whole-database encryption at rest. Protects a stolen disk or a copied
# backup. Losing this key means losing the database.
DATABASE_ENCRYPTION_KEY="${key()}"

# ---- field-level encryption ----
# Newest key first, comma separated: v2:<base64>,v1:<base64>
# Rotate by PREPENDING a new version. Old ciphertexts stay readable because
# every envelope names the version that sealed it.
OPENHAUL_KEYS="v1:${key()}"

# Pinned separately from OPENHAUL_KEYS. Changing it invalidates every blind
# index and requires re-indexing those columns in the same migration.
OPENHAUL_INDEX_KEY_VERSION="1"

# ---- passwords ----
# Held outside the database, so a database dump alone is useless.
# Rotating this invalidates every password, so treat it as append-only.
PASSWORD_PEPPER="${key()}"

# ---- application ----
NEXT_PUBLIC_APP_URL="http://localhost:3000"
# NEXT_PUBLIC_REPO_URL="https://github.com/you/openhaul"

# Required when running more than one instance: Next.js encrypts values that
# Server Actions close over with a per-build key, and separate instances would
# otherwise generate different keys and fail intermittently.
NEXT_SERVER_ACTIONS_ENCRYPTION_KEY="${key()}"

# Set when behind a reverse proxy that rewrites Host, or sign-in will fail
# with an origin mismatch. Also set \`proxy_set_header X-Forwarded-Host $host;\`
# ALLOWED_ORIGINS="openhaul.example.com"

# HSTS. Add includeSubDomains and preload only if you control every subdomain.
# HSTS_HEADER="max-age=31536000; includeSubDomains"
`;

await writeFile(target, contents, { mode: 0o600 });
console.log(`Wrote ${target}`);
console.log('Back up OPENHAUL_KEYS and DATABASE_ENCRYPTION_KEY somewhere safe.');
console.log('Losing them means losing every encrypted field and the database itself.');
